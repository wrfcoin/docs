# --------------------------------------------------------------------------
# Utilities
# --------------------------------------------------------------------------

def load_json(path: Path | None) -> dict | None:
    if not path:
        return None
    try:
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        sys.stderr.write(f"warn: failed to read {path}: {e}\n")
    return None


def first_h1(text: str) -> str:
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("# "):
            return line[2:].strip()
    return ""


def humanize_age(iso_ts: str | None) -> str:
    """Return a compact age string (e.g. '4h', '3d'). Returns '—' if unparseable."""
    if not iso_ts:
        return "—"
    try:
        ts = datetime.fromisoformat(iso_ts.replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return "—"
    delta = datetime.now(timezone.utc) - ts
    secs = int(delta.total_seconds())
    if secs < 0:
        return "now"
    if secs < 60:
        return f"{secs}s"
    if secs < 3600:
        return f"{secs // 60}m"
    if secs < 86400:
        return f"{secs // 3600}h"
    return f"{delta.days}d"


def format_int(value) -> str:
    if isinstance(value, int):
        return f"{value:,}"
    return str(value) if value is not None else "—"


# --------------------------------------------------------------------------
# Chapter scan
# --------------------------------------------------------------------------

def chapter_meta(md_path: Path) -> dict:
    stem = md_path.stem
    text = md_path.read_text(encoding="utf-8", errors="replace")
    ws, status, blurb = CHAPTER_MAP.get(stem, ("uncategorized", "drafted", ""))
    title = first_h1(text) or stem.replace("-", " ").title()
    title = re.sub(r"^\d+\.\s+", "", title)  # strip leading "1. " from chapter titles
    word_count = len(re.findall(r"\b\w+\b", text))
    questions = sum(
        1 for line in text.splitlines()
        if re.match(r"^\s*[-*]\s+", line) and ("?" in line or "TBD" in line.upper())
    )
    return {
        "slug": stem,
        "kind": "chapter",
        "workstream": ws,
        "status": status,
        "title": title,
        "blurb": blurb,
        "path": md_path.relative_to(REPO_DIR).as_posix(),
        "word_count": word_count,
        "open_questions": questions,
    }


def scan_chapters(chapter_dir: Path) -> list[dict]:
    return [chapter_meta(md) for md in sorted(chapter_dir.glob("[0-9][0-9]-*.md"))]


# --------------------------------------------------------------------------
# Wiki manifest
# --------------------------------------------------------------------------

def load_wiki_manifest(explicit: Path | None) -> dict | None:
    candidates = [explicit] if explicit else DEFAULT_WIKI_MANIFEST_CANDIDATES
    for c in candidates:
        if c is None:
            continue
        try:
            if c.exists():
                return json.loads(c.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
    return None


def derive_wiki_state(wiki_manifest: dict | None) -> dict:
    if not wiki_manifest or "entries" not in wiki_manifest:
        return {
            "available": False, "total": 0, "active": 0, "stub": 0, "review_needed": 0,
            "sources": 0, "open_questions": 0,
            "path_hint": "wiki/",
        }
    entries = wiki_manifest.get("entries", [])
    return {
        "available": True,
        "total": len(entries),
        "active":        sum(1 for e in entries if e.get("wiki_status") == "active"),
        "stub":          sum(1 for e in entries if e.get("wiki_status") == "stub"),
        "review_needed": sum(1 for e in entries if e.get("wiki_status") == "review-needed"),
        "sources":       sum(int(e.get("source_count", 0)) for e in entries),
        "open_questions": sum(int(e.get("open_questions", 0)) for e in entries),
        "path_hint": wiki_manifest.get("wiki_root", ""),
    }


