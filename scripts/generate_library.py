def chapter_cards_html(chapters: list[dict], wiki_entries: list[dict]) -> str:
    wiki_by_slug = {e.get("slug"): e for e in wiki_entries}
    out: list[str] = []
    for ch in chapters:
        num = ch["slug"].split("-")[0].lstrip("0") or "0"
        wiki_slug = CHAPTER_TO_WIKI_SLUG.get(ch["slug"])
        wiki_entry = wiki_by_slug.get(wiki_slug) if wiki_slug else None
        wiki_present = "true" if wiki_entry else "false"
        wiki_badge = "wiki ✓" if wiki_entry else "no wiki"
        open_q = wiki_entry.get("open_questions", ch.get("open_questions", 0)) if wiki_entry else ch.get("open_questions", 0)
        out.append(
            f'<article class="card card-chapter">'
            f'<div class="card-marginalia">Ch. {num}</div>'
            f'<h3 class="card-title"><a href="../{_html.escape(ch["path"])}">{_html.escape(ch["title"])}</a></h3>'
            f'<p class="card-blurb">{_html.escape(ch["blurb"])}</p>'
            f'<footer class="card-foot">'
            f'<span class="metric">{ch["word_count"]:,} words · {open_q} open</span>'
            f'<span class="metric metric-wiki" data-present="{wiki_present}">{wiki_badge}</span>'
            f'</footer>'
            f'</article>'
        )
    return "\n".join(out)


def wiki_section_html(wiki_entries: list[dict]) -> str:
    groups: dict[str, list[dict]] = {}
    for e in wiki_entries:
        if e.get("wiki_type") == "index":
            continue
        wt = e.get("wiki_type", "uncategorized")
        groups.setdefault(wt, []).append(e)

    sections: list[str] = []
    for group_name in WIKI_GROUP_ORDER:
        if group_name not in groups:
            continue
        entries = sorted(groups[group_name], key=lambda x: x.get("slug", ""))
        cards: list[str] = []
        for e in entries:
            status   = e.get("wiki_status", "stub")
            slug     = e.get("slug", "")
            title    = e.get("title", slug)
            wiki_path = e.get("wiki_path", "")
            # Link to wiki.html with a fragment; wiki.html doesn't exist yet, but
            # the link is future-proof. Falls back to a same-page anchor if needed.
            anchor    = wiki_path.replace("/", "-").replace(".md", "") if wiki_path else slug
            wiki_url  = f"wiki.html#{anchor}"
            open_q    = e.get("open_questions", 0)
            sources   = e.get("source_count", 0)
            updated   = e.get("last_updated", "—")
            review_html = ""  # placeholder until wiki manifest exports review_due
            cards.append(
                f'<article class="card card-wiki" data-status="{_html.escape(status)}">'
                f'<header class="card-head">'
                f'<h3 class="card-title"><a href="{_html.escape(wiki_url)}">{_html.escape(title)}</a></h3>'
                f'<span class="status-dot status-{_html.escape(status)}" title="{_html.escape(status)}"></span>'
                f'</header>'
                f'<dl class="card-stats">'
                f'<div><dt>open Q</dt><dd>{open_q}</dd></div>'
                f'<div><dt>src</dt><dd>{sources}</dd></div>'
                f'</dl>'
                f'<footer class="card-foot">'
                f'<span>{_html.escape(updated)}</span>'
                f'{review_html}'
                f'</footer>'
                f'</article>'
            )
        numeral = WIKI_GROUP_NUMERAL.get(group_name, "")
        tally   = f"{len(entries)} page" + ("s" if len(entries) != 1 else "")
        sections.append(
            f'<section class="wiki-group">'
            f'<h3 class="wiki-group-head">'
            f'<span class="wiki-group-name">'
            f'<span class="wiki-group-numeral">{numeral}</span>'
            f'<span>{_html.escape(group_name)}</span>'
            f'</span>'
            f'<span class="wiki-group-tally">{tally}</span>'
            f'</h3>'
            f'<div class="grid grid-wiki">'
            + "\n".join(cards)
            + '</div></section>'
        )
    return "\n".join(sections)


def repo_cards_html(repos: list[dict], wiki_entries: list[dict]) -> dict[str, str]:
    # Build a map: wiki_path-without-.md → entry
    wiki_by_pathstem: dict[str, dict] = {}
    for e in wiki_entries:
        p = e.get("wiki_path", "")
        if p.endswith(".md"):
            wiki_by_pathstem[p[:-3]] = e

    by_category: dict[str, list[str]] = {"active": [], "greenfield": [], "archived": []}

    for r in repos:
        category    = r.get("category", "active")
        status_cls  = category  # active / greenfield / archived map to dot colors
        name        = r["name"]
        stack       = r.get("stack", "—")
        role        = r.get("role", "—")
        open_prs    = r.get("open_prs", 0)
        ready       = r.get("prs_awaiting_merge", 0)
        last_push   = humanize_age(r.get("last_push"))
        key_metric  = r.get("key_metric", "")
        repo_url    = r.get("repo_url", f"https://github.com/wrfcoin/{name}")

        related = REPO_WIKI_MAP.get(name, [])
        link_chips: list[str] = []
        for slug_path in related:
            entry = wiki_by_pathstem.get(slug_path)
            if entry:
                anchor = entry["wiki_path"].replace("/", "-").replace(".md", "")
                link_chips.append(
                    f'<a class="wikilink" href="wiki.html#{_html.escape(anchor)}">{_html.escape(slug_path)}</a>'
                )
        wiki_links_html = " ".join(link_chips) if link_chips else '<span class="no-wiki">no wiki page yet</span>'

        card = (
            f'<article class="card card-repo" data-category="{_html.escape(category)}">'
            f'<header class="card-head">'
            f'<h3 class="card-title"><a href="{_html.escape(repo_url)}">{_html.escape(name)}</a></h3>'
            f'<span class="status-dot status-{_html.escape(status_cls)}" title="{_html.escape(category)}"></span>'
            f'</header>'
            f'<div class="card-stack">{_html.escape(stack)}</div>'
            f'<div class="card-role">{_html.escape(role)}</div>'
            f'<dl class="card-stats">'
            f'<div><dt>PRs</dt><dd>{open_prs}</dd></div>'
            f'<div><dt>ready</dt><dd>{ready}</dd></div>'
            f'<div><dt>push</dt><dd>{_html.escape(last_push)}</dd></div>'
            f'</dl>'
            f'<div class="card-keymetric">{_html.escape(key_metric)}</div>'
            f'<footer class="card-foot card-wikilinks">'
            f'{wiki_links_html}'
            f'</footer>'
            f'</article>'
        )
        by_category.setdefault(category, []).append(card)

    return {k: "\n".join(v) for k, v in by_category.items()}


# --------------------------------------------------------------------------
# Live-strip values
# --------------------------------------------------------------------------

def compute_testnet_strip(testnet_state: dict | None) -> dict:
    if not testnet_state or testnet_state.get("unreachable"):
        last_seen = (testnet_state or {}).get("last_seen_healthy")
        if last_seen:
            status_line = f"node unreachable · last seen {humanize_age(last_seen)} ago"
        else:
            status_line = "node unreachable · last seen never"
        return {
            "health_class": "unreachable",
            "status_line": status_line,
            "block": "—",
            "peers": "—",
            "last_block": "—",
        }
    summary = testnet_state.get("summary", {}) or {}
    healthy = summary.get("healthy", False)
    height  = summary.get("block_height")
    return {
        "health_class": "healthy" if healthy else "degraded",
        "status_line":  "healthy" if healthy else "degraded",
        "block": format_int(height) if height is not None else "—",
        "peers": format_int(summary.get("peer_count")),
        "last_block": humanize_age(summary.get("last_block_at")),
    }


def find_last_lint_date(wiki_manifest: dict | None) -> str:
    if not wiki_manifest:
        return "—"
    dates = [e.get("last_updated") for e in wiki_manifest.get("entries", []) if e.get("last_updated")]
    if not dates:
        return "—"
    return max(dates)


def find_next_review_due(wiki_manifest: dict | None) -> str:
    # The wiki manifest schema doesn't currently export review_due; placeholder until it does.
    if not wiki_manifest:
        return "—"
    return "—"


# --------------------------------------------------------------------------
# Template render + write
# --------------------------------------------------------------------------

def render(template: str, tokens: dict[str, str]) -> str:
    out = template
    for token, value in tokens.items():
        out = out.replace(token, value if value is not None else "")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--wiki-manifest", type=Path, default=None,
                        help="Path to wiki/data/wiki-manifest.json")
    parser.add_argument("--template", type=Path, default=DEFAULT_TEMPLATE)
    parser.add_argument("--output-html", type=Path, default=DEFAULT_OUTPUT_HTML)
    parser.add_argument("--output-data", type=Path, default=DEFAULT_OUTPUT_DATA)
    parser.add_argument("--repo-cache", type=Path, default=DEFAULT_REPO_CACHE)
    parser.add_argument("--testnet-cache", type=Path, default=DEFAULT_TESTNET_CACHE)
    args = parser.parse_args(argv)

    if not args.template.exists():
        sys.stderr.write(f"template not found: {args.template}\n")
        return 2

    chapters       = scan_chapters(DEFAULT_CHAPTER_DIR)
    wiki_manifest  = load_wiki_manifest(args.wiki_manifest)
    wiki_state     = derive_wiki_state(wiki_manifest)
    wiki_entries   = wiki_manifest.get("entries", []) if wiki_manifest else []
    repo_state     = load_json(args.repo_cache) or {}
    repos          = repo_state.get("repos", [])
    testnet_state  = load_json(args.testnet_cache)
    testnet_strip  = compute_testnet_strip(testnet_state)

    pr_open    = sum(r.get("open_prs", 0) for r in repos)
    pr_ready   = sum(r.get("prs_awaiting_merge", 0) for r in repos)
    commits_7d = sum(int(r.get("recent_commits_7d") or 0) for r in repos)

    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    repo_cards = repo_cards_html(repos, wiki_entries)

    tokens = {
        "{{ GENERATED_AT }}":              generated_at,
        "{{ TESTNET_BLOCK }}":             testnet_strip["block"],
        "{{ TESTNET_PEERS }}":             testnet_strip["peers"],
        "{{ TESTNET_LAST_BLOCK }}":        testnet_strip["last_block"],
        "{{ TESTNET_HEALTH_CLASS }}":      testnet_strip["health_class"],
        "{{ TESTNET_STATUS_LINE }}":       _html.escape(testnet_strip["status_line"]),
        "{{ PR_OPEN_TOTAL }}":             format_int(pr_open),
        "{{ PR_READY_TOTAL }}":            format_int(pr_ready),
        "{{ COMMITS_7D_TOTAL }}":          format_int(commits_7d),
        "{{ WIKI_ACTIVE }}":               str(wiki_state.get("active", 0)),
        "{{ WIKI_STUB }}":                 str(wiki_state.get("stub", 0)),
        "{{ WIKI_OPEN_Q }}":               str(wiki_state.get("open_questions", 0)),
        "{{ WIKI_SOURCES }}":              str(wiki_state.get("sources", 0)),
        "{{ WIKI_TOTAL }}":                str(wiki_state.get("total", 0)),
        "{{ LAST_LINT_DATE }}":            find_last_lint_date(wiki_manifest),
        "{{ NEXT_REVIEW_DUE }}":           find_next_review_due(wiki_manifest),
        "{{ REPO_COUNT }}":                str(len(repos)),
        "{{ CHAPTER_CARDS_HTML }}":        chapter_cards_html(chapters, wiki_entries),
        "{{ WIKI_SECTION_HTML }}":         wiki_section_html(wiki_entries),
        "{{ REPO_ACTIVE_CARDS_HTML }}":    repo_cards.get("active", ""),
        "{{ REPO_GREENFIELD_CARDS_HTML }}": repo_cards.get("greenfield", ""),
        "{{ REPO_ARCHIVED_CARDS_HTML }}":  repo_cards.get("archived", ""),
    }

    template_text = args.template.read_text(encoding="utf-8")
    rendered      = render(template_text, tokens)

    args.output_html.parent.mkdir(parents=True, exist_ok=True)
    args.output_html.write_text(rendered, encoding="utf-8")

    manifest = {
        "schema": "wrfcoin-library-manifest-v2",
        "generated_at": generated_at,
        "chapters": chapters,
        "wiki": wiki_state,
        "repos": repos,
        "testnet": testnet_strip,
        "live_strip": {
            "pr_open": pr_open,
            "pr_ready": pr_ready,
            "commits_7d": commits_7d,
            "last_lint": tokens["{{ LAST_LINT_DATE }}"],
        },
        "workstream_order": WORKSTREAM_ORDER,
        "status_order":     STATUS_ORDER,
    }
    args.output_data.parent.mkdir(parents=True, exist_ok=True)
    args.output_data.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"Wrote {args.output_html}")
    print(f"Wrote {args.output_data}")
    print(f"  chapters: {len(chapters)}")
    print(f"  wiki:     {'detected' if wiki_state['available'] else 'NOT detected'} ({wiki_state.get('total', 0)} pages · {wiki_state.get('open_questions', 0)} open Q)")
    print(f"  repos:    {len(repos)} ({sum(1 for r in repos if r.get('category')=='active')} active · {sum(1 for r in repos if r.get('category')=='greenfield')} greenfield · {sum(1 for r in repos if r.get('category')=='archived')} archived)")
    print(f"  testnet:  {testnet_strip['health_class']} ({testnet_strip['status_line']})")
    print(f"  live:     {pr_open} open PRs · {pr_ready} ready · {commits_7d} commits/7d")
    return 0


if __name__ == "__main__":
    sys.exit(main())
