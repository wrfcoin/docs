REPO_DIR = SCRIPT_DIR.parent
DEFAULT_TEMPLATE     = REPO_DIR / "site"  / "library.template.html"
DEFAULT_OUTPUT_HTML  = REPO_DIR / "site"  / "library.html"
DEFAULT_OUTPUT_DATA  = REPO_DIR / "data"  / "library-manifest.json"
DEFAULT_REPO_CACHE   = REPO_DIR / "cache" / "repo-state.json"
DEFAULT_TESTNET_CACHE = REPO_DIR / "cache" / "testnet-state.json"
DEFAULT_CHAPTER_DIR  = REPO_DIR / "whitepaper"

DEFAULT_WIKI_MANIFEST_CANDIDATES = [
    REPO_DIR / "wiki" / "data" / "wiki-manifest.json",
    REPO_DIR / "data" / "wiki-manifest.json",
]

