#!/usr/bin/env python3
"""Generate the WRFCoin Library — hybrid bridge over whitepaper chapters, the
WSL-side wiki, and the GitHub repos.

Reads:
  - whitepaper/0N-name.md chapter files
  - wiki/data/wiki-manifest.json (generated by wiki/scripts/generate_wiki_manifest.py)
  - cache/repo-state.json  (generated by scripts/fetch_repo_state.py)
  - cache/testnet-state.json (generated by scripts/fetch_testnet_state.py)
  - site/library.template.html (the design template with {{ TOKEN }} placeholders)

Writes:
  - site/library.html         (rendered public-facing page)
  - data/library-manifest.json (machine-readable inventory, v2 schema)

Usage:
  python3 scripts/generate_library.py
  python3 scripts/generate_library.py --wiki-manifest /path/to/wiki-manifest.json
"""

